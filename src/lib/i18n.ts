export const T: Record<Lang, TranslationKeys> = { en, de, fr, es, it, pl, ro, nl, pt, el, hu };

export function detectLang(): Lang {
  const saved = localStorage.getItem("dz_lang");
  if (saved && saved in T) return saved as Lang;

  const candidates: readonly string[] = navigator.languages?.length
    ? navigator.languages
    : [navigator.language];

  for (const tag of candidates) {
    const code = tag.slice(0, 2).toLowerCase();
    if (code in T) return code as Lang;
  }
  return "en";
}
